// Explicit country classification sets
const STATE_COUNTRY_CODES = new Set([
  "US", "NG", "AU", "DE", "IN", "BR", "MX", "MY", "AT", "FM", "MM", "PW", "SS", "SD", "VE", "ET", "SO"
]);

const COUNTY_COUNTRY_CODES = new Set([
  "GB", "IE", "KE", "HR", "HU", "RO", "LT", "EE", "NO", "SE"
]);

const EMIRATE_COUNTRY_CODES = new Set(["AE"]);
const CANTON_COUNTRY_CODES = new Set(["CH"]);
const REGION_COUNTRY_CODES = new Set([
  "FR", "GH", "MA", "NZ", "DK", "TZ", "UG", "SN", "CI", "CM", "PE", "CL", "BO", "UY", "PY"
]);

/**
 * Universal Country Code resolver matching any name or code from all 240+ countries.
 */
export function resolveCountryCode(countryCodeOrName: string): string {
  if (!countryCodeOrName) return "GB";
  const trimmed = countryCodeOrName.trim();
  if (trimmed.length === 2) {
    return trimmed.toUpperCase();
  }
  const match = COUNTRIES.find(
    (c) => c.name.toLowerCase() === trimmed.toLowerCase() || c.code.toLowerCase() === trimmed.toLowerCase()
  );
  if (match) return match.code;
  return trimmed.toUpperCase();
}

/**
 * Retrieves the subdivision configuration for a given country.
 * Detects whether the country uses "state", "province", or another subdivision,
 * returning the proper label, placeholder ("Select state" vs "Select province"), and subdivision list.
 */
export function getSubdivisionConfig(countryCodeOrName: string): SubdivisionConfig {
  const code = resolveCountryCode(countryCodeOrName);
  const config = SUBDIVISIONS_BY_CODE[code];
  if (config) {
    return config;
  }

  // Determine correct type & placeholder for countries without a hardcoded dropdown array
  if (STATE_COUNTRY_CODES.has(code)) {
    return {
      type: "state",
      label: "State",
      placeholder: "Select state",
      subdivisions: [],
      required: false,
    };
  }

  if (COUNTY_COUNTRY_CODES.has(code)) {
    return {
      type: "county",
      label: "County",
      placeholder: code === "GB" ? "County (optional)" : "Select county",
      subdivisions: [],
      required: false,
    };
  }

  if (EMIRATE_COUNTRY_CODES.has(code)) {
    return {
      type: "emirate",
      label: "Emirate",
      placeholder: "Select emirate",
      subdivisions: [],
      required: false,
    };
  }

  if (CANTON_COUNTRY_CODES.has(code)) {
    return {
      type: "canton",
      label: "Canton",
      placeholder: "Select canton",
      subdivisions: [],
      required: false,
    };
  }

  if (REGION_COUNTRY_CODES.has(code)) {
    return {
      type: "region",
      label: "Region",
      placeholder: "Select region",
      subdivisions: [],
      required: false,
    };
  }

  // Global default: Provinces (e.g. Canada, South Africa, China, Argentina, Philippines, Poland, Turkey, etc.)
  return {
    type: "province",
    label: "Province",
    placeholder: "Select province",
    subdivisions: [],
    required: false,
  };
}

export function isStateCountry(countryCodeOrName: string): boolean {
  const cfg = getSubdivisionConfig(countryCodeOrName);
  return cfg.type === "state";
}

export function isProvinceCountry(countryCodeOrName: string): boolean {
  const cfg = getSubdivisionConfig(countryCodeOrName);
  return cfg.type === "province";
}
